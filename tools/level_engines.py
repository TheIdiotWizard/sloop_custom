"""Calibrates the engines' levels (firmware/src/engine_trim.h: ENG_TRIM, 1/2 dB, the steps of LEVEL).

As in Felucca, a factory sound has no trim of its own and a chord is not cut by its voice count: the engines come out
alike, one number each, and the master limiter takes what a chord adds up to. The number brings the median loudness of the
engine's factory sounds (ITU-R BS.1770 integrated, gated, over the phrase that fits each sound: tests/preset_level.c: a bass
line, held chords, comping or a melody) to TARGET. TARGET sets the whole machine's loudness: lower, and the limiter works
less (tests/chord_probe.c shows the peaks that enter it).

  cc -O2 -Ibuild/gen -Ifirmware/src -Ifirmware/hal tests/preset_level.c -lm -o build/host/preset_level
  build/host/preset_level build/host/presets.wav build/host/presets.txt build/host/presets.raw
  tools/level_engines.py build/host/presets.raw build/host/presets.txt [--write]
  (rebuild and run it again: the numbers add to the ones in engine_trim.h; --write updates the file)
Needs numpy and scipy."""
import re
import sys
from pathlib import Path

import numpy as np
from scipy.signal import lfilter

FS, CTL = 44100, 32
SEG = (FS * 9 // 2) // CTL * CTL + (FS // 4) // CTL * CTL
OUT = Path(__file__).resolve().parent.parent / "firmware/src/engine_trim.h"
TARGET = -21.0                                 # LUFS (integrated), at the default LEVEL
ROLE = {0: 0.0, 1: -1.0, 2: 0.0, 3: 0.0, 4: 0.0}   # bass, chords held (pads, organs), comping, melody, one-key chords
SKIP = {"GM KIT"}                              # (the drum map on a synth track: as it is)
LO, HI = -40, 23                               # LEVEL 104 + 23 = 127: the top of the table


def lufs(x):
    b1 = [1.53512485958697, -2.69169618940638, 1.19839281085285]
    a1 = [1, -1.69065929318241, 0.73248077421585]
    b2, a2 = [1, -2, 1], [1, -1.99004745483398, 0.99007225036621]
    k = lfilter(b2, a2, lfilter(b1, a1, x)) ** 2
    w, h = int(0.4 * FS), int(0.1 * FS)
    bl = np.array([k[i:i + w].mean() for i in range(0, len(k) - w, h)])
    bl = bl[bl > 1e-7]
    if not len(bl):
        return None
    g = bl[10 * np.log10(bl) - 0.691 > -70]
    rel = 10 * np.log10(g.mean()) - 0.691 - 10
    g = g[10 * np.log10(g) - 0.691 > rel]
    return 10 * np.log10(g.mean()) - 0.691


def main(raw, rep, write):
    rows = [l.split(None, 3) for l in Path(rep).read_text().splitlines()]
    d = np.fromfile(raw, np.int32).astype(float) / 32768.0
    per = {}
    for i, (e, p, role, name) in enumerate(rows):
        if name in SKIP:
            continue
        v = lufs(d[i * SEG:(i + 1) * SEG])
        if v is not None:
            per.setdefault(int(e), []).append(v - ROLE[int(role)])
    old = [int(x) for x in re.findall(r"-?\d+", re.search(r"\{(.*?)\}", OUT.read_text()).group(1))]
    new = list(old)
    for e in sorted(per):
        vs = sorted(per[e])
        med = float(np.median(vs))
        new[e] = max(LO, min(HI, old[e] + int(round((TARGET - med) * 2))))
        print(f"engine {e}: {len(vs):2d} sounds, median {med:6.1f} LUFS, range {vs[0]:6.1f} .. {vs[-1]:6.1f}   trim {old[e]:3d} -> {new[e]:3d}")
    if write:
        OUT.write_text("/* generated by tools/level_engines.py: the level trim of each engine, 1/2 dB (ENGINES[] order) */\n#pragma once\n"
                       "static const int8_t ENG_TRIM[NENGINES] = {" + ", ".join(map(str, new)) + "};\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], "--write" in sys.argv)
